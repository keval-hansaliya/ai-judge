/**
 * Retrieves aggregate personal evaluation statistics for the authenticated user.
 */
export const getBattleStats = asyncHandler(async (req, res) => {
  const userId = req.user.id;

  const allBattles = await prisma.battle.findMany({
    where: { userId },
    select: {
      id: true,
      category: true,
      winner: true,
      createdAt: true
    }
  });

  const total = allBattles.length;
  let voted = 0;
  let unvoted = 0;
  let winsA = 0;
  let winsB = 0;
  let ties = 0;
  const categories = {};

  for (const b of allBattles) {
    categories[b.category] = (categories[b.category] || 0) + 1;
    if (b.winner) {
      voted++;
      if (b.winner === 'A') winsA++;
      else if (b.winner === 'B') winsB++;
      else if (b.winner === 'TIE') ties++;
    } else {
      unvoted++;
    }
  }

  let favoriteCategory = 'General';
  let maxCatCount = 0;
  for (const [cat, cnt] of Object.entries(categories)) {
    if (cnt > maxCatCount) {
      maxCatCount = cnt;
      favoriteCategory = cat;
    }
  }

  res.status(200).json(
    new ApiResponse(200, {
      totalBattles: total,
      votedBattles: voted,
      unvotedBattles: unvoted,
      votesDistribution: {
        modelA: winsA,
        modelB: winsB,
        tie: ties
      },
      favoriteCategory,
      categoriesBreakdown: categories
    }, "User battle statistics retrieved successfully")
  );
});
