export const voteBattle = asyncHandler(async (req, res) => {
  const battleId = parseInt(req.params.id);
  const { winner } = req.body; // Expected: "A", "B", "TIE"

  if (isNaN(battleId)) {
    throw new ApiError(400, "Invalid battle ID");
  }

  if (!["A", "B", "TIE"].includes(winner)) {
    throw new ApiError(400, "Winner must be either 'A', 'B', or 'TIE'");
  }

  // Execute database updates inside an atomic transaction with row locking
  const result = await prisma.$transaction(async (tx) => {
    // 1. Lock the battle row to prevent duplicate votes from race conditions
    const battles = await tx.$queryRaw`
      SELECT * FROM "Battle" WHERE id = ${battleId} FOR UPDATE
    `;
    const battle = battles[0];

    if (!battle) {
      throw new ApiError(404, "Battle not found");
    }

    if (battle.winner !== null) {
      throw new ApiError(409, "This battle has already been voted on");
    }

    // 2. Lock both model rows in the database to prevent concurrent rating calculation issues
    const models = await tx.$queryRaw`
      SELECT * FROM "Model" WHERE id IN (${battle.modelAId}, ${battle.modelBId}) FOR UPDATE
    `;

    const modelA = models.find(m => m.id === battle.modelAId);
    const modelB = models.find(m => m.id === battle.modelBId);

    if (!modelA || !modelB) {
      throw new ApiError(500, "Associated models for this battle could not be found");
    }

    // 3. Compute the new Elo ratings
    const { newRatingA, newRatingB } = calculateElo(modelA.elo, modelB.elo, winner);

    // 4. Determine wins, losses, and ties modifications
    let winsA = modelA.wins, lossesA = modelA.losses, tiesA = modelA.ties;
    let winsB = modelB.wins, lossesB = modelB.losses, tiesB = modelB.ties;

    if (winner === 'A') {
      winsA++;
      lossesB++;
    } else if (winner === 'B') {
      lossesA++;
      winsB++;
    } else if (winner === 'TIE') {
      tiesA++;
      tiesB++;
    }

    // 5. Update Model A stats & Elo
    await tx.model.update({
      where: { id: modelA.id },
      data: {
        elo: newRatingA,
        wins: winsA,
        losses: lossesA,
        ties: tiesA,
        totalBattles: modelA.totalBattles + 1
      }
    });

    // 6. Update Model B stats & Elo
    await tx.model.update({
      where: { id: modelB.id },
      data: {
        elo: newRatingB,
        wins: winsB,
        losses: lossesB,
        ties: tiesB,
        totalBattles: modelB.totalBattles + 1
      }
    });

    // 7. Update Battle status with the winner and timestamp
    const updatedBattle = await tx.battle.update({
      where: { id: battle.id },
      data: {
        winner,
        votedAt: new Date()
      }
    });

    // 8. Return response containing true model identities now that voting is complete
    return {
      battleId: updatedBattle.id,
      winner: updatedBattle.winner,
      modelA: {
        name: modelA.name,
        oldElo: modelA.elo,
        newElo: newRatingA
      },
      modelB: {
        name: modelB.name,
        oldElo: modelB.elo,
        newElo: newRatingB
      }
    };
  });

  res.status(200).json(
    new ApiResponse(200, result, "Vote recorded and Elo ratings updated successfully")
  );
});

/**
 * Retrieves paginated list of battles for the authenticated user with optional filters.
 */
export const getBattles = asyncHandler(async (req, res) => {
  const page = Math.max(1, parseInt(req.query.page) || 1);
  const limit = Math.min(50, Math.max(1, parseInt(req.query.limit) || 10));
  const skip = (page - 1) * limit;
  const { category, winner, search } = req.query;

  const where = {
    userId: req.user.id
  };

  if (category && category !== 'All') {
    where.category = category;
  }

  if (winner) {
    if (winner === 'unvoted') {
      where.winner = null;
    } else {
      where.winner = winner.toUpperCase();
    }
  }

  if (search && search.trim()) {
    where.prompt = {
      contains: search.trim(),
      mode: 'insensitive'
    };
  }

  const [total, battles] = await Promise.all([
    prisma.battle.count({ where }),
    prisma.battle.findMany({
      where,
      skip,
      take: limit,
      orderBy: { createdAt: 'desc' },
      include: {
        modelA: {
          select: { id: true, name: true, provider: true, modelId: true, elo: true }
        },
        modelB: {
          select: { id: true, name: true, provider: true, modelId: true, elo: true }
        }
      }
    })
  ]);

  const sanitizedBattles = battles.map(b => {
    const isVoted = b.winner !== null;
    return {
      id: b.id,
      prompt: b.prompt,
      category: b.category,
      createdAt: b.createdAt,
      winner: b.winner,
      votedAt: b.votedAt,
      turnsCount: Array.isArray(b.turns) ? b.turns.length : 1,
      modelA: isVoted ? b.modelA : { name: "Model A", provider: "Blind" },
      modelB: isVoted ? b.modelB : { name: "Model B", provider: "Blind" },
      isVoted
    };
  });

  res.status(200).json(
    new ApiResponse(200, {
      battles: sanitizedBattles,
      pagination: {
        total,
        page,
        limit,
        totalPages: Math.ceil(total / limit)
      }
    }, "Battles retrieved successfully")
  );
});

/**
 * Retrieves full conversation turns and details of a specific battle.
 */
export const getBattleById = asyncHandler(async (req, res) => {
  const battleId = parseInt(req.params.id);
  if (isNaN(battleId)) {
    throw new ApiError(400, "Invalid battle ID");
  }

  const battle = await prisma.battle.findFirst({
    where: {
      id: battleId,
      userId: req.user.id
    },
    include: {
      modelA: true,
      modelB: true
    }
  });

  if (!battle) {
    throw new ApiError(404, "Battle not found");
  }

  const isVoted = battle.winner !== null;

  const result = {
    id: battle.id,
    prompt: battle.prompt,
    category: battle.category,
    responseA: battle.responseA,
    responseB: battle.responseB,
    turns: Array.isArray(battle.turns) ? battle.turns : [
      { turn: 1, prompt: battle.prompt, responseA: battle.responseA, responseB: battle.responseB }
    ],
    winner: battle.winner,
    votedAt: battle.votedAt,
    createdAt: battle.createdAt,
    modelA: isVoted ? battle.modelA : { id: battle.modelA.id, name: "Model A", provider: "Blind" },
    modelB: isVoted ? battle.modelB : { id: battle.modelB.id, name: "Model B", provider: "Blind" },
    isVoted
  };

  res.status(200).json(
    new ApiResponse(200, result, "Battle details retrieved successfully")
  );
});

