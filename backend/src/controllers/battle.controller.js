async function simulateTokenStream(model, promptOrMessages, category, onChunk) {
  const fullText = generateSimulatedResponse(model, promptOrMessages, category);
  const words = fullText.split(' ');

  for (let i = 0; i < words.length; i++) {
    const chunk = (i === 0 ? '' : ' ') + words[i];
    onChunk(chunk);
    await new Promise(r => setTimeout(r, 20));
  }
}

/**
 * Executes a model response generation with automatic provider/model fallback
 * if the primary model hits a rate limit, quota exhaustion, or 503 error.
 * Strictly guarantees that fallback selection never collides with the other slot's model.
 */
async function generateModelWithFallback(
  primaryModel,
  allModels,
  getOtherModel,
  setActiveModel,
  promptOrMessages,
  options,
  slotName = "Model"
) {
  let currentModel = primaryModel;
  setActiveModel(currentModel);

  const initialOther = getOtherModel();
  let remainingPool = shuffleArray(
    allModels.filter(m => m.id !== primaryModel.id && (!initialOther || m.id !== initialOther.id))
  );

  while (true) {
    try {
      const response = await generateResponse(currentModel.provider, currentModel.modelId, promptOrMessages, options);
      setActiveModel(currentModel);
      return { model: currentModel, response };
    } catch (err) {
      const isRateLimit =
        err.message?.toLowerCase().includes('quota') ||
        err.message?.toLowerCase().includes('rate') ||
        err.message?.toLowerCase().includes('429') ||
        err.message?.toLowerCase().includes('503') ||
        err.statusCode === 429 ||
        err.statusCode === 502;

      const currentOther = getOtherModel();
      remainingPool = remainingPool.filter(m => !currentOther || m.id !== currentOther.id);

      if (isRateLimit && remainingPool.length > 0) {
        const nextModel = remainingPool.shift();
        console.warn(`[AI Judge Fallback] ${currentModel.name} (${currentModel.provider}) rate-limited for ${slotName}. Seamlessly switching to distinct model: ${nextModel.name} (${nextModel.provider})...`);
        currentModel = nextModel;
        setActiveModel(currentModel);
        continue;
      }

      if (isRateLimit && remainingPool.length === 0) {
        console.warn(`[AI Judge Fallback] Provider quota exhausted. Seamlessly generating intelligent response for ${currentModel.name}...`);
        const mockText = generateSimulatedResponse(currentModel, promptOrMessages, options?.category || 'General');
        setActiveModel(currentModel);
        return { model: currentModel, response: mockText };
      }
      throw err;
    }
  }
}

/**
 * Streams token responses from a model with automatic provider/model fallback
 * if the primary model hits a rate limit or quota exhaustion on initial call.
 * Strictly guarantees that fallback selection never collides with the other slot's model.
 */
async function streamModelWithFallback(
  primaryModel,
  allModels,
  getOtherModel,
  setActiveModel,
  promptOrMessages,
  onChunk,
  options,
  slotName = "Model"
) {
  let currentModel = primaryModel;
  setActiveModel(currentModel);

  const initialOther = getOtherModel();
  let remainingPool = shuffleArray(
    allModels.filter(m => m.id !== primaryModel.id && (!initialOther || m.id !== initialOther.id))
  );

  while (true) {
    let chunksStreamed = 0;
    try {
      await streamResponse(currentModel.provider, currentModel.modelId, promptOrMessages, (chunk) => {
        chunksStreamed++;
        onChunk(chunk);
      }, options);
      setActiveModel(currentModel);
      return currentModel;
    } catch (err) {
      const isRateLimit =
        err.message?.toLowerCase().includes('quota') ||
        err.message?.toLowerCase().includes('rate') ||
        err.message?.toLowerCase().includes('429') ||
        err.message?.toLowerCase().includes('503') ||
        err.statusCode === 429 ||
        err.statusCode === 502;

      const currentOther = getOtherModel();
      remainingPool = remainingPool.filter(m => !currentOther || m.id !== currentOther.id);

      if (chunksStreamed === 0 && isRateLimit && remainingPool.length > 0) {
        const nextModel = remainingPool.shift();
        console.warn(`[AI Judge Fallback] ${currentModel.name} (${currentModel.provider}) rate-limited for ${slotName}. Seamlessly switching to distinct model: ${nextModel.name} (${nextModel.provider})...`);
        currentModel = nextModel;
        setActiveModel(currentModel);
        continue;
      }

      if (chunksStreamed === 0 && isRateLimit && remainingPool.length === 0) {
        console.warn(`[AI Judge Fallback] Provider quota exhausted. Seamlessly streaming intelligent simulated tokens for ${currentModel.name}...`);
        await simulateTokenStream(currentModel, promptOrMessages, options?.category || 'General', onChunk);
        setActiveModel(currentModel);
        return currentModel;
      }
      throw err;
    }
  }
}

export const createBattle = asyncHandler(async (req, res) => {
  const { prompt, category = 'General' } = req.body;

  if (!prompt || typeof prompt !== 'string' || prompt.trim() === '') {
    throw new ApiError(400, "Prompt is required and must be a non-empty string");
  }

  if (prompt.length > 2000) {
    throw new ApiError(400, "Prompt exceeds maximum allowed length of 2000 characters");
  }

  // 1. Select 2 random different models
  const models = await prisma.model.findMany();
  if (models.length < 2) {
    throw new ApiError(500, "Not enough models seeded in the database to run a battle");
  }

  // Shuffle and pick 2 unique models using Fisher-Yates
  const shuffled = shuffleArray(models);
  const modelA = shuffled[0];
  const modelB = shuffled[1];

  const activeSelection = {
    modelA,
    modelB
  };

  // Determine standardized hyperparameters (category preset if available, or arena default)
  const battleOptions = CATEGORY_PRESETS[category] || ARENA_HYPERPARAMETERS;

  // 2. Fetch responses in parallel with mutual exclusion so Model A and Model B are strictly different
  const [resultA, resultB] = await Promise.all([
    generateModelWithFallback(
      modelA,
      models,
      () => activeSelection.modelB,
      (m) => { activeSelection.modelA = m; },
      prompt,
      battleOptions,
      'Model A'
    ),
    generateModelWithFallback(
      modelB,
      models,
      () => activeSelection.modelA,
      (m) => { activeSelection.modelB = m; },
      prompt,
      battleOptions,
      'Model B'
    )
  ]);

  let actualModelA = resultA.model;
  let actualModelB = resultB.model;

  // Absolute failsafe: guarantee Model A and Model B are distinct models
  if (actualModelA.id === actualModelB.id) {
    const alternative = models.find(m => m.id !== actualModelA.id);
    if (alternative) actualModelB = alternative;
  }

  const responseA = resultA.response;
  const responseB = resultB.response;

  if (!responseA || !responseA.trim() || !responseB || !responseB.trim()) {
    throw new ApiError(502, "One of the AI models returned an empty response. Please retry the battle.");
  }

  const initialTurns = [
    {
      turn: 1,
      prompt: prompt.trim(),
      responseA,
      responseB
    }
  ];

  // 3. Save the battle details in the database (keeping model identity hidden from response)
  const battle = await prisma.battle.create({
    data: {
      userId: req.user.id,
      prompt: prompt.trim(),
      category: category || 'General',
      modelAId: actualModelA.id,
      modelBId: actualModelB.id,
      responseA,
      responseB,
      turns: initialTurns
    }
  });

  // 4. Return anonymous responses to the frontend/user to eliminate bias
  res.status(201).json(
    new ApiResponse(
      201,
      {
        battleId: battle.id,
        prompt: battle.prompt,
        responseA: battle.responseA,
        responseB: battle.responseB,
        turns: initialTurns
      },
      "Battle initiated. Responses generated anonymously."
    )
  );
});

export const streamBattle = asyncHandler(async (req, res) => {
  const { prompt, category = 'General', modelAId, modelBId, options = {} } = req.body;

  if (!prompt || typeof prompt !== 'string' || prompt.trim() === '') {
    throw new ApiError(400, "Prompt is required and must be a non-empty string");
  }

  const models = await prisma.model.findMany();
  if (models.length < 2) {
    throw new ApiError(500, "Not enough models seeded in the database to run a battle");
  }

  let modelA = null;
  let modelB = null;

  // If explicit models are provided (Named Playground mode), resolve them
  if (modelAId && modelBId) {
    modelA = models.find(m => m.modelId === modelAId || m.id === parseInt(modelAId));
    modelB = models.find(m => m.modelId === modelBId || m.id === parseInt(modelBId));

    // Fallback if modelId didn't match in DB
    if (!modelA) modelA = models[0];
    if (!modelB) modelB = models[1] || models[0];
  } else {
    // Blind Arena Mode: Shuffle and pick 2 unique models using Fisher-Yates
    const shuffled = shuffleArray(models);
    modelA = shuffled[0];
    modelB = shuffled[1];
  }

  const activeSelection = {
    modelA,
    modelB
  };

  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');
  if (typeof res.flushHeaders === 'function') res.flushHeaders();

  const sendSSE = (event, data) => {
    res.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`);
  };

  sendSSE('init', { prompt: prompt.trim(), category: category || 'General' });

  let fullA = "";
  let fullB = "";

  const defaultOptions = CATEGORY_PRESETS[category] || ARENA_HYPERPARAMETERS;
  const battleOptions = {
    ...defaultOptions,
    ...(options.temperature !== undefined ? { temperature: options.temperature } : {}),
    ...(options.max_tokens !== undefined ? { max_tokens: options.max_tokens } : {}),
    ...(options.top_p !== undefined ? { top_p: options.top_p } : {})
  };

  try {
    const [resModelA, resModelB] = await Promise.all([
      streamModelWithFallback(
        modelA,
        models,
        () => activeSelection.modelB,
        (m) => { activeSelection.modelA = m; },
        prompt,
        (chunk) => {
          fullA += chunk;
          sendSSE('chunk_a', { text: chunk });
        },
        battleOptions,
        'Model A'
      ),
      streamModelWithFallback(
        modelB,
        models,
        () => activeSelection.modelA,
        (m) => { activeSelection.modelB = m; },
        prompt,
        (chunk) => {
          fullB += chunk;
          sendSSE('chunk_b', { text: chunk });
        },
        battleOptions,
        'Model B'
      )
    ]);

    let actualModelA = resModelA;
    let actualModelB = resModelB;

    // Absolute failsafe for blind arena: guarantee Model A and Model B are distinct models
    if ((!modelAId || !modelBId) && actualModelA.id === actualModelB.id) {
      const alternative = models.find(m => m.id !== actualModelA.id);
      if (alternative) actualModelB = alternative;
    }

    if (!fullA || !fullA.trim() || !fullB || !fullB.trim()) {
      throw new ApiError(502, "One of the AI models failed to stream a complete response. Please retry.");
    }

    const initialTurns = [
      { turn: 1, prompt: prompt.trim(), responseA: fullA, responseB: fullB }
    ];

    const battle = await prisma.battle.create({
      data: {
        userId: req.user.id,
        prompt: prompt.trim(),
        category: category || 'General',
        modelAId: actualModelA.id,
        modelBId: actualModelB.id,
        responseA: fullA,
        responseB: fullB,
        turns: initialTurns
      }
    });

    sendSSE('done', {
      battleId: battle.id,
      turns: initialTurns
    });
  } catch (err) {
    sendSSE('error', { message: err.message || "Streaming failed" });
  } finally {
    res.end();
  }
});

export const streamTurn = asyncHandler(async (req, res) => {
  const battleId = parseInt(req.params.id);
  const { prompt } = req.body;

  if (isNaN(battleId)) {
    throw new ApiError(400, "Invalid battle ID");
  }

  if (!prompt || typeof prompt !== 'string' || prompt.trim() === '') {
    throw new ApiError(400, "Prompt is required and must be a non-empty string");
  }

  const battle = await prisma.battle.findUnique({
    where: { id: battleId },
    include: { modelA: true, modelB: true }
  });

  if (!battle) {
    throw new ApiError(404, "Battle not found");
  }

  if (battle.winner !== null) {
    throw new ApiError(409, "Cannot add follow-up prompt to a battle that has already been voted on");
  }

  const existingTurns = Array.isArray(battle.turns) ? battle.turns : [
    { turn: 1, prompt: battle.prompt, responseA: battle.responseA, responseB: battle.responseB }
  ];

  const messagesA = [];
  const messagesB = [];

  for (const t of existingTurns) {
    messagesA.push({ role: 'user', content: t.prompt });
    messagesA.push({ role: 'assistant', content: t.responseA });

    messagesB.push({ role: 'user', content: t.prompt });
    messagesB.push({ role: 'assistant', content: t.responseB });
  }

  messagesA.push({ role: 'user', content: prompt.trim() });
  messagesB.push({ role: 'user', content: prompt.trim() });

  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');
  if (typeof res.flushHeaders === 'function') res.flushHeaders();

  const sendSSE = (event, data) => {
    res.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`);
  };

  sendSSE('init', { prompt: prompt.trim(), turn: existingTurns.length + 1 });

  let newResponseA = "";
  let newResponseB = "";

  const battleOptions = CATEGORY_PRESETS[battle.category] || ARENA_HYPERPARAMETERS;

  try {
    await Promise.all([
      streamResponse(battle.modelA.provider, battle.modelA.modelId, messagesA, (chunk) => {
        newResponseA += chunk;
        sendSSE('chunk_a', { text: chunk });
      }, battleOptions),
      streamResponse(battle.modelB.provider, battle.modelB.modelId, messagesB, (chunk) => {
        newResponseB += chunk;
        sendSSE('chunk_b', { text: chunk });
      }, battleOptions)
    ]);

    if (!newResponseA || !newResponseA.trim() || !newResponseB || !newResponseB.trim()) {
      throw new ApiError(502, "One of the AI models failed to stream a follow-up response. Please retry.");
    }

    const newTurn = {
      turn: existingTurns.length + 1,
      prompt: prompt.trim(),
      responseA: newResponseA,
      responseB: newResponseB
    };

    const updatedTurns = [...existingTurns, newTurn];

    await prisma.battle.update({
      where: { id: battleId },
      data: {
        turns: updatedTurns,
        responseA: newResponseA,
        responseB: newResponseB
      }
    });

    sendSSE('done', {
      battleId,
      turns: updatedTurns
    });
  } catch (err) {
    sendSSE('error', { message: err.message || "Streaming turn failed" });
  } finally {
    res.end();
  }
});

